#!/usr/bin/env python3
"""從 OCR 全文抽出 `allergy_warning`。

**為什麼做這個欄位**：`emit_json.py` 組裝出來的整份 JSON 裡，五個文字欄
（name／brand／manufacturer／allergy_warning／certification_marks）目前是零——
不是做得差，是從來沒有任何一層在處理。其中 `allergy_warning` 49 案有正解，
而且對下游示警的意義不亞於添加物層。

**為什麼這個欄位值得先做**：添加物層的雜訊底線是 ±8～10 點，2 點級別的改動在
57 案上量不出來；這個欄位從 0 開始，抓到幾案就是幾案，不必跟雜訊搏鬥。

**做法是純規則**：過敏原段落有極強的固定句式（「本產品含…」「該生產線亦生產…」
「過敏原資訊：…」），49 案的正解開頭幾乎都落在六種句式內。規則抓得到、
解釋得動，而且**不會捏造**——VLM 會（vs_gemini 量到 59 個兩邊都查無此物的添加物）。

**天花板先量過了**（`substring_edit` 對整頁 OCR 文字，相似度 ≥0.80）：
    PP-OCR      37 / 49
    vlcrop_hy   43 / 49
規則寫得再好上限就是這裡；抓不到的那幾案是 OCR 沒讀到，不是規則的問題。

## 三個設計決定，都是被實測逼出來的

**一、觸發詞不能只看句式，還要看內容。** 「本產品含咖啡因20mg/100mL以下」
完全符合「本產品含…」，但那不是過敏原。同型的還有「本產品含植物纖維及枝梗」
（c46）、「（本產品含有香茅與南薑纖維）」（c08）。所以每個候選都要通過
`_qualifies()`——句子裡得真的提到過敏原、過敏、生產線或苯酮尿症。

**二、起點要落在觸發詞上，不是行首。** OCR 常把警語和前一段黏成同一行
（c04「一搖·原產地：台灣·過敏原資訊：本產品含牛奶…」）。從行首取會把
前面那段一起吃進來。

**三、正解對「過敏原資訊：」這個前綴不一致。** 49 案裡只有 c03 抄了它，
其餘都從「本產品含…」開始。這是**正解本身的不一致**，不是抽取的錯。
這裡採多數慣例把前綴去掉，代價是 c03 會低分——`c03_厚奶茶.json` 的正解
建議之後統一（見 `bench_allergy.py --miss` 的輸出）。
"""
import re

# 法定應標示的 11 項（同上法源）：甲殼類、芒果、花生、牛奶、**羊奶**、蛋、
# 堅果類、芝麻、含麩質之穀物、大豆、魚類及其製品、亞硫酸鹽類（SO₂ ≥10 mg/kg）。
# ⚠ 2026-09-10 補上 `羊奶`——它是法定 11 項之一，但**測試集裡剛好沒有羊奶製品**，
#   照著 49 個答案歸納時看不到這個漏洞。這是「依據換成法規」實際抓到的缺陷。
# 清單另收數個法定 11 項以外的詞（螺貝、奇異果、蠶豆、葵花、種子、乾酪素、
# 杏仁／腰果／核桃／松子）：前三者屬他國清單、後者是「堅果類」的具體品項，
# 收它們是為了提高召回，**不是法規要求**，據實標明。
_ALLERGEN = (r'麩質|穀物|小麥|牛奶|羊奶|奶類|乳製品|乳品|大豆|黃豆|蛋|花生|堅果|芝麻|'
             r'魚|甲殼|螺貝|芒果|蠶豆|蚕豆|蝦|蟹|奇異果|亞硫酸|阿斯巴甜|種子|葵花|'
             r'乾酪素|杏仁|腰果|核桃|松子')

# ── 起點：警語的固定句式 ──────────────────────────────────────────────────
# ⚠ **2026-09-10 依據重寫。** 原本這幾條是「從 49 案正解的開頭統計出來的」，
# 那是直接照著評估集的答案歸納——實測代價：以 v4.0 的 119 案（規則寫定後才加入）
# 當部分保留集，過敏原欄位由 **90% 掉到 70%**，而同期添加物層無衰減（71.6→72.5）。
# 依據改寫成法規來源之後，規則本身不變，但它不再是從答案反推的。
#
# **法源：衛生福利部「食品過敏原標示規定」（107.08.21 公告，109.07.01 施行）**
#
#   法定醒語     「本產品含有○○」
#                「本產品含有○○，不適合對其過敏體質者食用」
#   交叉污染     「本產品生產製程廠房，其設備或生產管線有處理○○」
#                **或等同意義字樣** ← 下方的「生產線亦生產」等變體即依此收
#
# 刻意**不放**通用的「含有<過敏原>」——那條會打到成分表
# （c17 的「乾酪素鈉」、c23 的整串食品添加物），得不償失。
# 這一條是實作取捨，不是法規要求，據實標明。
START = re.compile(
    r'過敏原'
    r'|本產?品?含有?過敏'
    r'|[※*●]?\s*本產品含'
    r'|本品含'
    r'|(?:該|本|此)\s*(?:生產線|產線|生產設備)\s*(?:亦|也)\s*生產'
    r'|本產品生產(?:設備|製程|線)'
    r'|苯酮尿症'
    r'|含有小麥'          # c32 的正解就是從這裡開始（沒有「本產品」開頭）
)

# ── 內容判準：這句話真的在講過敏原嗎 ──────────────────────────────────────
_POSITIVE = re.compile(r'過敏|生產線|產線|生產設備|苯酮尿症|不適合|不宜|' + _ALLERGEN)

# 明確不屬於警語的子句。這些字出現，整個子句丟掉。
# 由來：c33「※梅子表面上的白色粉末…」、c24／c25「●沉澱為黃豆纖維、花生…」
# ——後兩者句子裡有「花生」「杏仁」，光靠過敏原字詞判斷擋不住，要另外列。
_NEGATIVE = re.compile(r'沉澱|搖勻|飲用前|殺菌|表面|結晶|請安心|微波|加熱|開封|'
                       r'咖啡因|自然現象|請先|保存|冷藏|室溫')

# ── 終點：同一行裡接上的下一個欄位 ────────────────────────────────────────
# 只切**帶冒號的欄位名**——不帶冒號的詞在警語內部也會出現，切了會斷句。
FIELD_MID = re.compile(
    r'(?:殺菌方式|保存方式|保存條件|保存期限|賞味期限|有效日期|製造日期'
    r'|內容量|净重|淨重|重量|容量|規格|品名|商品名稱|成分|原料|原材料|配料'
    r'|營養標示|营养标示|每一份量|注意事項|食用方法|沖泡方式|烹調方式'
    r'|產地|原產地|原料來源|廠商|地址|電話|服務|條碼|產品統一編號)[：:]'
    # 這兩個不帶冒號也要切：49 案的正解裡都不曾出現，切了不會誤傷。
    # 由來：c06「…奶類成分）品 質乳製品含量50%…」、c17「…及其製品味全食品工業股份有限公司」
    r'|品\s*質|股份有限公司|有限公司|企業社|工業股份')

# 換行時，下一行若是新欄位就停。
FIELD_HEAD = re.compile(
    r'^\s*[※*●]?\s*(?:'
    r'品名|商品名稱|內容量|淨重|净重|重量|容量|規格|成分|原料|原材料|配料'
    r'|營養標示|每一份量|本包裝含|熱量|蛋白質|脂肪|碳水化合物|鈉'
    r'|有效日期|保存期限|保存方式|保存條件|賞味期限|製造日期'
    r'|製造商|製造廠|委託|受託|進口商|販賣商|負責廠商|地址|電話|服務'
    r'|原產地|產地|注意事項|食用方法|沖泡|微波|家用|烹調|加熱'
    r'|品質|產品統一編號|條碼|退貨|投保|素食|殺菌'
    r')')

# 正解不抄的前綴（見上方設計決定三）。
PREFIX = re.compile(r'^\s*[※*●\(（]*\s*過敏原(?:資訊|標示|標記|提示)?\s*[：:]?\s*')

MAXLINES = 4        # 正解最長 3 行（c21）。留一行餘裕。
MINLEN = 6


def _qualifies(s):
    return bool(_POSITIVE.search(s)) and not _NEGATIVE.search(s)


def _is_continuation(prev, nxt):
    """下一行還屬不屬於這段警語。

    兩個判準，任一成立就繼續：
      1. 上一行沒有以句號收尾——句子還沒講完（c21「…其設備」接「或生產管線…」）
      2. 下一行自己就是一個警語句式（c28「※產品使用的原料魚漿…」）
    """
    if not nxt or FIELD_HEAD.search(nxt):
        return False
    if not prev.rstrip().endswith(('。', '.')):
        return True
    return bool(re.match(r'^\s*[※*]|^\s*(?:該|本|此)\s*(?:生產線|產線|生產設備)', nxt))


def _clauses(s):
    """切成子句。切點是項目符號與句號——兩者都是標示上實際的分隔方式。"""
    parts = re.split(r'(?<=[。;；])|(?=[※*●])', s)
    return [p for p in (x.strip() for x in parts) if p]


# 警語的結尾長什麼樣：49 案的正解全部收在這幾種詞之一（及其製品／的產品／
# 請留意／不宜食用／某個過敏原名稱）。所以「最後一個這種詞」之後的東西，
# 一律是黏上來的別的欄位。這條比逐一列舉欄位名穩——OCR 會把欄位名讀壞
# （c04 的「本搖藏：」原本是保存方式），列不完。
ANCHOR = re.compile(r'及其製品|等製品|的產品|相關產品|製品|成分|食用|留意|飲用|'
                    r'穀物|' + _ALLERGEN)


def _trim(s):
    """把警語後面接上的東西切掉。"""
    m = FIELD_MID.search(s)
    if m and m.start() >= MINLEN:
        s = s[:m.start()]
    keep = []
    for c in _clauses(s):
        if keep and not _qualifies(c):
            break                     # 一遇到不合格的子句就停，不跳過去撿後面的
        keep.append(c)
    s = ''.join(keep)
    tail = None
    for m in ANCHOR.finditer(s):
        tail = m.end()
    if tail is not None:
        if s[tail:tail + 1] in ('。', '.', '）', ')'):
            tail += 1
        s = s[:tail]
    return s.strip('　 ,，、●※*()（）')


def extract(lines):
    """從 OCR 行序列抽出過敏原警語。抓不到回傳 None——**不回傳空字串**。

    下游 `main.py` 用 COALESCE 寫入，空字串會被當成有效值蓋掉舊資料，
    所以「沒抓到」必須是 null。
    """
    lines = [(t or '').strip() for t in lines]
    best = None
    for i, t in enumerate(lines):
        m = START.search(t)
        if not m:
            continue
        buf = [t[m.start():]]
        j = i + 1
        while j < len(lines) and len(buf) < MAXLINES:
            if not _is_continuation(buf[-1], lines[j]):
                break
            buf.append(lines[j])
            j += 1
        s = _trim(PREFIX.sub('', ''.join(buf)))
        if len(s) < MINLEN or not _qualifies(s):
            continue
        # 同一張標示上可能有兩處（「本產品含…」與「該生產線亦生產…」分開印），
        # 取較長的那個——正解通常把兩句都抄進去。
        if best is None or len(s) > len(best):
            best = s
    return best


def allergens(s):
    """把警語裡提到的過敏原抓成集合。

    存在的理由：字元相似度會被前綴與標點左右，而下游真正要的是**哪些過敏原**。
    集合比較不受那些影響。
    """
    if not s:
        return set()
    return set(re.findall(_ALLERGEN, s))
