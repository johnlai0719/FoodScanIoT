def block(title, lines, sources):
    out = ["", "> **%s｜%s】**" % (MARK, title), ">"]
    for l in lines:
        out.append("> " + l if l else ">")
    out.append(">")
    out.append("> *出處：*")
    for what, where in sources:
        out.append("> - %s — `%s`" % (what, where))
    out.append("")
    return out


