def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    if "全量原稿保留" in a.src:
        sys.exit("這份不是原稿（相對於 docx 抽出稿已改寫 48 行、新增 166 行且未標註）。\n"
                 "請用 大專生計畫_extracted.md。")

    text = io.open(a.src, encoding="utf-8").read()
    if MARK in text:
        sys.exit("原稿裡已經有擴充標記——請以乾淨的原稿為輸入，避免重複插入。")
    lines = text.split("\n")

    inserts = []
    for anchor, before, title, body, srcs in EXPANSIONS:
        idx = [i for i, l in enumerate(lines) if anchor in l]
        if len(idx) != 1:
            sys.exit("錨點命中 %d 次（需剛好 1 次）：%s" % (len(idx), anchor[:40]))
        inserts.append((idx[0] if before else idx[0] + 1, block(title, body, srcs)))

    # 已否決一節接在最後一塊擴充之後
    rej = ["", "> **%s｜已評估並否決的替代方案】**" % MARK, ">",
           "> 下列方案均曾實作並於同一測試集上量測，因結果不支持而未採用。",
           "> 本節的目的在於說明設計選擇的取捨依據，而非列舉失敗。", ">"]
    for name, why, src in REJECTED:
        rej.append("> **%s**" % name)
        rej.append("> %s" % why)
        rej.append("> *出處：*`%s`" % src)
        rej.append(">")
    rej.append("")
    inserts.append((inserts[-1][0], rej))

    # 由後往前插，行號才不會位移
    for at, blk in sorted(inserts, key=lambda x: -x[0]):
        lines[at:at] = blk

    io.open(a.out, "w", encoding="utf-8").write("\n".join(lines))
    print("已寫出 %s" % a.out)
    print("插入 %d 個擴充區塊 ＋ 1 節已否決（共 %d 項）。原文未更動。"
          % (len(EXPANSIONS), len(REJECTED)))


if __name__ == "__main__":
    main()
