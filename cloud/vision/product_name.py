#!/usr/bin/env python3
"""從 OCR 全文抽出 `name`（品名）。

**正解規則**（`正解欄位定義.md` 2026-09-02 定案）：**以標示的品名欄為準，
逐字抄，不任意增刪品牌名稱。** 所以「麥香紅茶」的品名欄寫什麼就填什麼，
不必補「統一」；需要品牌時去讀 `brand`。這條規則讓抽取變成單純的
「找到品名欄，抄完整行」。

**天花板（2026-09-07 量，兩讀取器聯集）**：

    正解有 name                 173
    全文含正解（完全字串）        137 (79.2%)
    有「品名／名稱」錨點          134 (77.5%)
    正解剛好是完整獨立的一行        26 (15.0%)

錨點率幾乎等於天花板，所以**這欄靠錨點就夠**，跟 `manufacturer` 只有
52.7% 有錨點的情況不同。

**沒有錨點的 39 案（22.5%）這支不處理，回 None。** 那些要靠「字最大、
在最上面」判斷，需要文字框；而 `vlcrop_hy_v4` 的 6306 行**全部沒有 box**
（rec 是 HunyuanOCR，不吐框），只有 PP-OCR 的輸出有座標。要做的話是另一
條路：從 `out/v6_best` 的 box 高度排序取最大的幾行。**先不做**——
`manufacturer.py` 的教訓是沒把握就別給，C 類欄位猜錯會直接記成一次錯誤。

## 兩個從資料逼出來的規則

**一、錨點要容忍第一個字被讀丟。** `c02` 的 OCR 是「名：無加糖濃豆漿」
（「品」沒讀到），`c03` 是「名：義美奶茶」。所以 bare 的「名」也收，
但**必須後面接冒號**——不然「品名」以外的「名」會打到一堆東西。
這跟 `bench_ingredients` 的 HEAD 容忍「料：」「分：」是同一個問題、同一個解。

**二、只取到行尾。** 品名欄後面接的一定是別的欄位（內容量、原料、有效日期），
而 OCR 幾乎都會在欄位之間斷行。跨行接續在這裡是有害的——`c01` 的下一行
就是「內容量：650毫升」。
"""
import re

ANCHOR = re.compile(
    r'(?:品\s*名|產品名稱|产品名称|商品名稱|品項名稱|名\s*稱|^名|[\s·。、]名)'
    r'\s*[:：]')

# 品名欄後面常見的鄰居；OCR 偶爾不斷行就靠這些切
STOP = re.compile(
    r'內容量|内容量|淨重|净重|容量|重量|成\s*分|原\s*料|材料|有效|保存|賞味|'
    r'製造|廠商|地址|電話|產地|原產地|每一份量|本包裝|營養|過敏|規格|類別|品類')

_LEAD = re.compile(r'^[\s:：·、,，.。／/|~\-─—│\]】）)]+')
_TAIL = re.compile(r'[\s:：·、,，.。／/|~\-─—│\[【（(]+$')


def _one(line, pos):
    seg = _LEAD.sub('', line[pos:])
    cut = STOP.search(seg)
    if cut:
        seg = seg[:cut.start()]
    seg = _TAIL.sub('', seg)
    return seg if 2 <= len(seg) <= 40 else None


def extract(lines):
    """回傳品名或 None（**不回傳空字串**，理由同 `allergy.py`）。

    逐行找錨點，取該行錨點之後的內容。找到第一個合格的就回傳——
    品名欄在標示上只有一個，多找幾個只會找到「原料名稱」這類鄰居。
    """
    for ln in lines or []:
        ln = (ln or '').strip()
        m = ANCHOR.search(ln)
        if not m:
            continue
        v = _one(ln, m.end())
        if v:
            return v
    return None


def merge(cands):
    """多讀取器擇一：**依傳入順序取第一個非空的**，不比長度。

    四種合併方式在 173 案上實測（完全對／命中）：

        PP-OCR 優先   104 / 118      ← 用這個
        相同才給      104 / 118
        vlcrop 優先    97 / 118
        取較長         96 / 116

    命中數幾乎一樣，但「取較長」的完全對少 8 案——長的那個常是把下一個
    欄位吃進來的版本。這跟 `manufacturer` 相反（那邊的病是截斷，取長有用），
    所以**兩支不能共用同一條合併規則**。呼叫端要把 PP-OCR 放前面：
    品名印在包裝正面，不在成分區裡，整張圖的讀取器本來就該贏。
    """
    for v in cands:
        if v:
            return v
    return None
